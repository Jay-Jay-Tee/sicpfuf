// node tests/ui.cjs /path/to/node_modules/jsdom
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { execFileSync } = require('node:child_process');
const { JSDOM } = require(resolve(process.argv[2] || 'node_modules/jsdom'));
const root = resolve(__dirname, '..');
const html = readFileSync(resolve(root, 'sicpfuf/ui/index.html'), 'utf8');
const js = readFileSync(resolve(root, 'sicpfuf/ui/ui.js'), 'utf8');
const dom = new JSDOM(html, { url: 'http://127.0.0.1:8765/', runScripts: 'outside-only' });
const w = dom.window, doc = w.document;
const get = id => doc.getElementById(id);
const style = doc.createElement('style');
style.textContent = readFileSync(resolve(root, 'sicpfuf/ui/ui.css'), 'utf8');
doc.head.append(style);
const source = 'def square(x):\n    return x * x\nprint(square(2 + 1))\n';
const timers = new Map();
let timer = 0;
let playbackDelay = null;
w.setInterval = (callback, delay) => { playbackDelay = delay; timers.set(++timer, callback); return timer; };
w.clearInterval = id => timers.delete(id);
w.fetch = async (path, options) => {
  if (path === '/api/session') return { ok: true, json: async () => ({ source, filename: 'sample.py', chapter: 2, mode: 'environment' }) };
  assert.equal(path, '/api/trace');
  const data = options.body;
  const result = JSON.parse(execFileSync('python3', ['-m', 'sicpfuf.ui', '--trace'], { cwd: root, input: data }));
  return { ok: true, json: async () => result };
};
const wait = () => new Promise(resolve => setTimeout(resolve, 20));
const change = node => node.dispatchEvent(new w.Event('change'));
const seekEnd = () => { get('position').value = get('position').max; get('position').dispatchEvent(new w.Event('input')); };
(async () => {
  w.eval(js);
  await wait();
  assert.equal(get('code').value, source);
  assert.equal(get('filename').textContent, 'sample.py');
  assert.equal(get('syntax').textContent, source + '\n');
  assert.equal(get('syntax').querySelector('.tok-keyword').textContent, 'def');
  assert.ok(get('diagram').querySelector('svg'));
  const builtins = get('diagram').querySelector('[data-builtins]');
  assert.ok(builtins);
  builtins.dispatchEvent(new w.MouseEvent('click', { bubbles: true }));
  assert.match(get('inspection').textContent, /Built-ins · pre-declared names/);
  get('clear-inspection').click();
  const naturalWidth = parseFloat(get('diagram').querySelector('svg').style.width);
  get('zoom-in').click();
  assert.ok(parseFloat(get('diagram').querySelector('svg').style.width) > naturalWidth);
  get('zoom-fit').click();
  assert.equal(get('zoom-fit').textContent, 'Fit');
  Object.defineProperties(get('diagram'), { clientWidth: { value: 640, configurable: true }, clientHeight: { value: 240, configurable: true } });
  get('zoom-fit').click();
  assert.ok(parseFloat(get('diagram').querySelector('svg').style.height) <= 200);
  get('zoom-actual').click();
  assert.equal(parseFloat(get('diagram').querySelector('svg').style.width), Number(get('diagram').querySelector('svg').getAttribute('viewBox').split(' ')[2]));
  get('zoom-fit').click();
  get('next').click();
  assert.equal(get('event-kind').textContent, 'BEFORE');
  get('next').click();
  assert.match(get('message').textContent, /Defined square/);
  get('view-program').click();
  assert.equal(get('diagram').hidden, true);
  assert.equal(get('program-view').hidden, false);
  assert.match(get('remaining-program').textContent, /print\(square\(/);
  get('view-diagram').click();
  assert.equal(get('program-view').hidden, true);
  const frame = get('diagram').querySelector('[data-frame]');
  frame.dispatchEvent(new w.MouseEvent('click', { bubbles: true }));
  assert.equal(get('inspection').hidden, false);
  assert.match(get('inspection').textContent, /square = #1/);
  assert.equal(get('inspection-panel').hidden, false);
  assert.ok(get('diagram').querySelector('.pointer-trace'));
  assert.match(get('bindings').textContent, /square#1/);
  get('clear-inspection').click();
  assert.equal(get('inspection-panel').hidden, true);
  assert.equal(get('diagram').querySelector('.pointer-trace'), null);
  get('play').click();
  assert.equal(timers.size, 1);
  assert.equal(playbackDelay, 900);
  get('speed').value = '450'; change(get('speed'));
  assert.equal(timers.size, 1);
  assert.equal(playbackDelay, 450);
  [...timers.values()][0]();
  get('play').click();
  assert.equal(timers.size, 0);
  while ((get('event-kind').textContent !== 'AFTER' || !/Called square/.test(get('message').textContent)) && !get('next').disabled) get('next').click();
  assert.equal(get('frame-name').textContent, 'E1');
  assert.equal(get('bindings').textContent, 'x3');
  const fn = get('diagram').querySelector('[data-function]');
  fn.focus();
  assert.equal(w.getComputedStyle(fn).outline, 'none');
  fn.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
  assert.match(get('inspection').textContent, /#1/);
  fn.dispatchEvent(new w.MouseEvent('dblclick', { bubbles: true }));
  assert.notEqual(get('zoom-fit').textContent, 'Fit');
  fn.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  assert.equal(get('inspection-panel').hidden, true);
  const canvas = get('diagram');
  canvas.scrollLeft = 80; canvas.scrollTop = 60;
  canvas.dispatchEvent(new w.MouseEvent('pointerdown', { button: 0, clientX: 100, clientY: 100, bubbles: true }));
  canvas.dispatchEvent(new w.MouseEvent('pointermove', { clientX: 70, clientY: 80, bubbles: true }));
  canvas.dispatchEvent(new w.MouseEvent('pointerup', { bubbles: true }));
  assert.equal(canvas.scrollLeft, 110); assert.equal(canvas.scrollTop, 80);
  canvas.dispatchEvent(new w.MouseEvent('click', { bubbles: true }));
  const widthBeforeWheel = parseFloat(canvas.querySelector('svg').style.width);
  canvas.dispatchEvent(new w.WheelEvent('wheel', { ctrlKey: true, deltaY: -100, bubbles: true, cancelable: true }));
  assert.ok(parseFloat(canvas.querySelector('svg').style.width) > widthBeforeWheel);
  const position = get('position').value;
  get('code').dispatchEvent(new w.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
  assert.equal(get('position').value, position); // editing arrows never step
  doc.body.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
  assert.equal(Number(get('position').value), Number(position) + 1);
  seekEnd();
  assert.equal(get('output').textContent, '9\n');
  get('back').click();
  assert.notEqual(get('position').value, get('position').max);
  get('mode').value = 'substitution'; change(get('mode'));
  assert.equal(get('next').disabled, true);
  get('run').click(); await wait();
  assert.equal(get('diagram').hidden, true);
  assert.equal(get('reduction').hidden, false);
  assert.equal(get('frame-panel').hidden, true);
  get('next').click(); get('next').click(); get('next').click();
  assert.ok(get('after').querySelector('mark'));
  seekEnd();
  assert.equal(get('output').textContent, '9\n');
  get('mode').value = 'environment'; change(get('mode'));
  get('chapter').value = '4'; change(get('chapter'));
  get('typed').checked = true; change(get('typed'));
  get('code').value = 'x: int = "wrong"\nprint("should not run")\n';
  get('code').dispatchEvent(new w.Event('input'));
  get('run').click(); await wait();
  assert.match(get('error').textContent, /StaticTypeError/);
  assert.equal(get('run-state').textContent, 'Stopped');
  assert.equal(get('event-kind').textContent, 'STOPPED');
  assert.equal(get('output').textContent, 'No output yet.');
  assert.equal(get('position').value, get('position').max);
  get('code').value = 'x: int = 3\nprint(x * x)\n';
  get('code').dispatchEvent(new w.Event('input'));
  get('run').click(); await wait(); seekEnd();
  assert.equal(get('error').hidden, true);
  assert.equal(get('output').textContent, '9\n');
  get('typed').checked = false; change(get('typed'));
  get('code').value = 'print(input("Name: "))\n';
  get('stdin').value = 'Ada\n';
  get('code').dispatchEvent(new w.Event('input'));
  get('run').click(); await wait(); seekEnd();
  assert.equal(get('output').textContent, 'Name: Ada\n');
  get('code').value = 'print(7)\nprint(1 / 0)\n';
  get('code').dispatchEvent(new w.Event('input'));
  assert.equal(get('next').disabled, true);
  get('code').dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Enter', ctrlKey: true, bubbles: true }));
  await wait(); seekEnd();
  assert.equal(get('output').textContent, '7\n');
  assert.match(get('error').textContent, /ZeroDivisionError/);
  get('code').value = 'print("<img src=x onerror=alert(1)>") # comment\n';
  get('code').dispatchEvent(new w.Event('input'));
  assert.equal(get('syntax').querySelector('img'), null);
  assert.equal(get('syntax').querySelector('.tok-string').textContent, '"<img src=x onerror=alert(1)>"');
  w.fetch = async () => { throw new Error('Connection closed'); };
  get('run').click(); await wait();
  assert.match(get('error').textContent, /Connection closed/);
  assert.equal(get('run').disabled, false);
  w.close();
  console.log('Built-in UI checks passed: both models, Typed checking, input, syntax colours, bindings, zoom, inspection, playback speed, keyboard navigation, rewind, edits, and errors.');
})().catch(error => { console.error(error); w.close(); process.exit(1); });
