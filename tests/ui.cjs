// node tests/ui.cjs /path/to/node_modules/jsdom
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { execFileSync } = require('node:child_process');
const { JSDOM } = require(resolve(process.argv[2] || 'node_modules/jsdom'));
const root = resolve(__dirname, '..');
const html = readFileSync(resolve(root, 'sicpfuf/ui/index.html'), 'utf8');
const js = readFileSync(resolve(root, 'sicpfuf/ui/ui.js'), 'utf8');
const dom = new JSDOM(html, { url: 'http://127.0.0.1:8765/', runScripts: 'outside-only' });
const w = dom.window, doc = w.document;
const get = id => doc.getElementById(id);
const source = 'def square(x):\n    return x * x\nprint(square(2 + 1))\n';
const timers = new Map();
let timer = 0;
w.setInterval = callback => { timers.set(++timer, callback); return timer; };
w.clearInterval = id => timers.delete(id);
w.fetch = async (path, options) => {
  if (path === '/api/session') return { ok: true, json: async () => ({ source, filename: 'sample.py', chapter: 2, mode: 'environment' }) };
  assert.equal(path, '/api/trace');
  const data = options.body;
  const result = JSON.parse(execFileSync('python3', ['-m', 'sicpfuf.ui', '--trace'], { cwd: root, input: data }));
  return { ok: true, json: async () => result };
};
const wait = () => new Promise(resolve => setTimeout(resolve, 20));
const change = node => node.dispatchEvent(new w.Event('change'));
const seekEnd = () => { get('position').value = get('position').max; get('position').dispatchEvent(new w.Event('input')); };
(async () => {
  w.eval(js);
  await wait();
  assert.equal(get('code').value, source);
  assert.equal(get('filename').textContent, 'sample.py');
  assert.ok(get('diagram').querySelector('svg'));
  get('next').click();
  assert.match(get('message').textContent, /Defined square/);
  const frame = get('diagram').querySelector('[data-frame]');
  frame.dispatchEvent(new w.MouseEvent('click', { bubbles: true }));
  assert.equal(get('inspection').hidden, false);
  assert.match(get('inspection').textContent, /square = fn#1/);
  get('play').click();
  assert.equal(timers.size, 1);
  [...timers.values()][0]();
  get('play').click();
  assert.equal(timers.size, 0);
  seekEnd();
  assert.equal(get('output').textContent, '9\n');
  get('back').click();
  assert.notEqual(get('position').value, get('position').max);
  get('mode').value = 'substitution'; change(get('mode'));
  assert.equal(get('next').disabled, true);
  get('run').click(); await wait();
  assert.equal(get('diagram').hidden, true);
  assert.equal(get('reduction').hidden, false);
  get('next').click(); get('next').click(); get('next').click();
  assert.ok(get('after').querySelector('mark'));
  seekEnd();
  assert.equal(get('output').textContent, '9\n');
  get('code').value = 'print(7)\nprint(1 / 0)\n';
  get('code').dispatchEvent(new w.Event('input'));
  assert.equal(get('next').disabled, true);
  get('code').dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Enter', ctrlKey: true, bubbles: true }));
  await wait(); seekEnd();
  assert.equal(get('output').textContent, '7\n');
  assert.match(get('error').textContent, /ZeroDivisionError/);
  w.fetch = async () => { throw new Error('Connection closed'); };
  get('run').click(); await wait();
  assert.match(get('error').textContent, /Connection closed/);
  assert.equal(get('run').disabled, false);
  w.close();
  console.log('Built-in UI checks passed: initial file, both models, diagrams, inspection, playback, rewind, edits, and errors.');
})().catch(error => { console.error(error); w.close(); process.exit(1); });
