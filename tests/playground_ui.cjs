const { JSDOM } = require(require('node:path').resolve(process.argv[2] || 'node_modules/jsdom'));
const fs = require('fs');
const assert = require('node:assert/strict');
const { execFileSync } = require('child_process');
const root = require('node:path').resolve(__dirname, '..');
const site = require('node:path').resolve(process.argv[3] || 'site');
const examples = JSON.parse(fs.readFileSync(site + '/assets/playground-traces.json'));
const environmentExamples = examples.filter(e => !e.mode || e.mode === 'environment');
const substitutionExamples = examples.filter(e => e.mode === 'substitution');
const source = fs.readFileSync(site + '/assets/playground.js', 'utf8');
const wait = () => new Promise(r => setTimeout(r, 20));
function makeWindow(html, path = '/sicpfuf/playground/') {
  const dom = new JSDOM(html, { url: 'https://example.test' + path, runScripts: 'outside-only', pretendToBeVisual: true });
  const w = dom.window;
  Object.defineProperty(w.document, 'currentScript', { value: { src: 'https://example.test/sicpfuf/assets/playground.js' } });
  w.fetch = async () => ({ ok: true, json: async () => examples });
  w.HTMLElement.prototype.scrollIntoView = function () {};
  w.labTimers = new Map();
  let timerId = 0;
  w.setInterval = (callback, delay) => { w.labTimers.set(++timerId, { callback, delay }); return timerId; };
  w.clearInterval = id => w.labTimers.delete(id);
  w.Worker = class {
    constructor() { w.lastWorker = this; }
    postMessage(data) {
      const trace = JSON.parse(execFileSync('python3', ['-c', 'import sys,json; from sicpfuf.xray.playground import trace; d=json.load(sys.stdin); print(json.dumps(trace(d["source"],d["chapter"],d.get("mode","environment"))))'], { cwd: root, input: JSON.stringify(data) }));
      setTimeout(() => { if (!this.terminated) this.onmessage({ data: { type: 'result', trace } }); }, 1);
    }
    terminate() { this.terminated = true; }
  };
  return w;
}
